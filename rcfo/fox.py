_PIXELS = zlib.decompress(base64.b85decode(_DATA))


def _art(width, height, color):
    """Area-average the embedded portrait, preserving its silhouette."""
    rows = []
    for y in range(height):
        row = []
        for x in range(width):
            xa, xb = x * _SOURCE_W // width, (x + 1) * _SOURCE_W // width
            ya, yb = y * _SOURCE_H // height, (y + 1) * _SOURCE_H // height
            rgb = [0, 0, 0]
            count = 0
            for sy in range(ya, max(ya + 1, yb)):
                for sx in range(xa, max(xa + 1, xb)):
                    offset = (sy * _SOURCE_W + sx) * 3
                    for c in range(3):
                        rgb[c] += _PIXELS[offset + c]
                    count += 1
            rgb = [v / count for v in rgb]
            light = min(255, max(0, (0.299 * rgb[0] + 0.587 * rgb[1] + 0.114 * rgb[2]) * 1.46 - 4))
            char = _RAMP[int((light / 255) ** 0.68 * (len(_RAMP) - 1))] if light > 3 else " "
            if color and char != " ":
                warm = [min(255, int(255 * (v / 255) ** 0.62 * 1.28)) for v in rgb]
                row.append("\x1b[38;2;{};{};{}m{}".format(*warm, char))
            else:
                row.append(char)
        rows.append("".join(row) + ("\x1b[0m" if color else ""))
    return rows
